package com.syc.adquisiciones;

public class DatosCaso {

	
	private String folioConsolidado = null;
	private String folioPrecompromiso= null;
	private String descripcion = null;
	private String fechaFin= null;
	public String getFolioConsolidado() {
		return folioConsolidado;
	}
	public void setFolioConsolidado(String folioConsolidado) {
		this.folioConsolidado = folioConsolidado;
	}
	public String getFolioPrecompromiso() {
		return folioPrecompromiso;
	}
	public void setFolioPrecompromiso(String folioPrecompromiso) {
		this.folioPrecompromiso = folioPrecompromiso;
	}
	public String getDescripcion() {
		return descripcion;
	}
	public void setDescripcion(String descripcion) {
		this.descripcion = descripcion;
	}
	public String getFechaFin() {
		return fechaFin;
	}
	public void setFechaFin(String fechaFin) {
		this.fechaFin = fechaFin;
	}

	
	
}
