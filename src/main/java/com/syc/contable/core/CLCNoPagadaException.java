package com.syc.contable.core;

public class CLCNoPagadaException extends Exception {

	private static final long	serialVersionUID	= -1150011214474886388L;

	public CLCNoPagadaException() {
		super();
	}

	public CLCNoPagadaException(String message, Throwable cause) {
		super(message, cause);
	}

	public CLCNoPagadaException(String message) {
		super(message);
	}

	public CLCNoPagadaException(Throwable cause) {
		super(cause);
	}

}
