package com.axtel.contratos.core;


public class OtrosImpuestos {
	private int nId;
	private String cImpuesto;
	private double mMonto;
	
	public int getnId() {
		return nId;
	}
	
	public void setnId( int nId ) {
		this.nId = nId;
	}
	
	public String getcImpuesto() {
		return cImpuesto;
	}
	
	public void setcImpuesto( String cImpuesto ) {
		this.cImpuesto = cImpuesto;
	}
	
	public double getmMonto() {
		return mMonto;
	}
	
	public void setmMonto( double mMonto ) {
		this.mMonto = mMonto;
	}
	
	
}
